def classify(defekt_type, desc):
    """-> (характер работы, узел). Оба могут быть «(не классифицировано)»."""
    t = norm(desc)
    if not t:
        return '(описание пустое)', '(описание пустое)'
    kind = '(не классифицировано)'
    for name, keys in KIND:
        if any(k in t for k in keys):
            kind = name
            break
    node = '(не классифицировано)'
    for name, keys in NODES.get(defekt_type, []):
        if any(k in t for k in keys):
            node = name
            break
    return kind, node
